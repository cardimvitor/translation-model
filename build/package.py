def ascii_js(src, dst):
    subprocess.run([sys.executable, os.path.join(ROOT, "build", "ascii_js.py"), src, dst], check=True)


def add_tree(z, src, arc):
    if os.path.isdir(src):
        for r, _, fs in os.walk(src):
            for f in fs:
                p = os.path.join(r, f); z.write(p, os.path.join(arc, os.path.relpath(p, src)))
    else:
        z.write(src, arc)


def build(name, files, readme):
    path = os.path.join(DIST, name)
    tmp = os.path.join(DIST, "_js"); os.makedirs(tmp, exist_ok=True)
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for src, arc in files:
            if src.endswith(".js") and "/runtime/" in src:
                t = os.path.join(tmp, os.path.basename(src)); ascii_js(src, t); z.write(t, arc)
            else:
                add_tree(z, src, arc)
        z.writestr("README.md", readme)
    shutil.rmtree(tmp, ignore_errors=True)
    print(name, round(os.path.getsize(path) / 1e6, 1), "MB zipped")


def main(report):
    R = lambda *p: os.path.join(ROOT, *p)
    check = [(R("data", "encheck.json"), "data/encheck.json"), (R("runtime", "encheck.js"), "runtime/encheck.js"),
             (R("runtime", "encheck.py"), "runtime/encheck.py"), (R("runtime", "normalizer.py"), "runtime/normalizer.py")]
    build("en-check.zip", check, report["check"] + LICENSES)
    fast = [(R("data"), "data")] + [(R("runtime", f), f"runtime/{f}") for f in ("normalizer.js", "normalizer.py", "encheck.js", "encheck.py")] + \
        [(R("test", f), f"test/{f}") for f in ("cases.json", "blind.json", "run_any.py", "parity.js", "make_parity_inputs.py")]
    build("en-normalizer-fast.zip", fast, report["fast"] + LICENSES)
    acc = fast + [(R("runtime", f), f"runtime/{f}") for f in ("student.js", "student.py", "accurate.js", "accurate.py")] + \
        [(R("models", "student", f), f"models/student/{f}") for f in ("encoder_int8.onnx", "decoder_int8.onnx", "vocab.json")] + \
        [(R("node_modules", "onnxruntime-web", "dist", f), f"ort/{f}") for f in ("ort.wasm.min.js", "ort-wasm-simd-threaded.mjs", "ort-wasm-simd-threaded.wasm")]
    build("en-normalizer-accurate.zip", acc, report["accurate"] + LICENSES + ACC_LICENSES)


if __name__ == "__main__":
    main(json.load(open(os.path.join(DIST, "readmes.json"), encoding="utf-8")))
